/// Схема планировки этажа — задаёт стратегию расстановки комнат.
///
/// Выбирается пользователем на этапе 1 (брифа) и используется
/// генератором планов [FloorPlanGenerator] для подбора стратегии
/// расстановки комнат.
enum LayoutScheme {
  /// Коридорная: магистральный коридор делит этаж на два «банка»;
  /// все комнаты выходят в коридор. Универсальная схема для ИЖС.
  corridor,

  /// Анфиладная: комнаты идут одна за другой, проходные двери
  /// между ними; коридор отсутствует. Для парадных классических домов.
  enfilade,

  /// Зальная: одна большая центральная общественная зона
  /// (гостиная-столовая-кухня), служебные/спальные — по периметру.
  hall,

  /// Квартирная (студия): кухня + столовая + гостиная объединены
  /// в одно открытое пространство, спальни и санузел компактно сбоку.
  studio,

  /// Компактная (центральное ядро): лестница, санузел и котельная
  /// собраны в центральном ядре, жилые комнаты — по внешнему периметру.
  centralCore;

  String get title {
    switch (this) {
      case LayoutScheme.corridor:
        return 'Коридорная';
      case LayoutScheme.enfilade:
        return 'Анфиладная';
      case LayoutScheme.hall:
        return 'Зальная';
      case LayoutScheme.studio:
        return 'Квартирная (студия)';
      case LayoutScheme.centralCore:
        return 'Компактная (центральное ядро)';
    }
  }

  String get description {
    switch (this) {
      case LayoutScheme.corridor:
        return 'Универсальная схема: магистральный коридор посередине, '
            'комнаты по обе стороны. Каждая комната имеет свой выход.';
      case LayoutScheme.enfilade:
        return 'Парадная схема: комнаты идут одна за другой, '
            'проходные двери, без коридора. Подходит для домов '
            'с большими общественными зонами.';
      case LayoutScheme.hall:
        return 'Большая центральная зала-гостиная объединяет дом, '
            'спальни и санузел — по периметру. Подходит для '
            'компактных домов до 100 м².';
      case LayoutScheme.studio:
        return 'Открытое жилое пространство: кухня, столовая и '
            'гостиная без перегородок, спальни в стороне. '
            'Современный загородный коттедж.';
      case LayoutScheme.centralCore:
        return 'Ядро в центре (лестница, санузел, котельная), жилые '
            'комнаты — по внешнему периметру с лучшим освещением. '
            'Энергоэффективная компактная схема.';
    }
  }

  static LayoutScheme fromName(String? name) {
    if (name == null) return LayoutScheme.corridor;
    return LayoutScheme.values.firstWhere(
      (s) => s.name == name,
      orElse: () => LayoutScheme.corridor,
    );
  }
}
