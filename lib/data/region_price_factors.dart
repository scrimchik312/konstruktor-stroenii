/// Каталог приоритетов: вернуть конкретный коэффициент для города.
double regionFactorFor(String? city) {
  if (city == null || city.isEmpty) return kRegionFactorDefault;
  final direct = kCityFactors[city];
  if (direct != null) return direct;
  // Резервно — ищем город в каталоге и пытаемся подобрать округ.
  for (final r in kRegionCatalog) {
    if (r.city == city) {
      // По снеговой/ветровой зоне определять округ ненадёжно — пропустим.
      // Возвращаем нейтральный коэффициент.
      return kRegionFactorDefault;
    }
  }
  return kRegionFactorDefault;
}

